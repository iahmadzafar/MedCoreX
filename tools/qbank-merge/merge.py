"""Run the whole merge: extract, match, classify, mint, emit, gate.

Usage: python merge.py [--out DIR]
Exit code 0 means every gate passed.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import constants as C
import emit
from classify import classify, label_is_trusted
from extract import is_wellformed, load_canonical, load_legacy
from match import dedupe_within, link
from mint import mint_ids
from verify import run_gates


def _review_markdown(ambiguous, withheld, duplicates, malformed) -> str:
    lines = ["# Merge review — records withheld from the bank", ""]
    total = len(ambiguous) + len(withheld) + len(duplicates) + len(malformed)
    lines.append(
        f"Generated by `tools/qbank-merge/merge.py`. {total} records are not in the served bank."
    )
    lines.append("")

    lines.append(f"## Ambiguous variants ({len(ambiguous)})")
    lines.append("")
    lines.append("Same vignette as a canonical question, but keyed to a different answer that appears nowhere in the bank.")
    lines.append("")
    if ambiguous:
        lines.append("| bank | keyed answer | stem |")
        lines.append("| --- | --- | --- |")
        for item in ambiguous:
            key = item["legacy"].get("options") or []
            idx = item["legacy"].get("answer")
            answer = key[idx] if isinstance(idx, int) and 0 <= idx < len(key) else ""
            lines.append(f"| {item['legacy']['bank']} | {answer[:60]} | {item['legacy']['stem'][:110]} |")
    lines.append("")

    lines.append(f"## Withheld for low classification confidence ({len(withheld)})")
    lines.append("")
    if withheld:
        lines.append("| bank | label | system | confidence | stem |")
        lines.append("| --- | --- | --- | --- | --- |")
        for item in withheld:
            rec = item["legacy"]
            cls = item["classification"]
            lines.append(f"| {rec['bank']} | {rec['subject_label'][:28]} | {cls['system']} | {cls['confidence']} | {rec['stem'][:100]} |")
    lines.append("")

    lines.append(f"## Duplicate copies within the additions ({len(duplicates)})")
    lines.append("")
    lines.append("The same vignette appears twice in the legacy banks. The first copy was kept.")
    lines.append("")
    if duplicates:
        lines.append("| bank | kept as | stem |")
        lines.append("| --- | --- | --- |")
        for item in duplicates:
            rec = item["legacy"]
            lines.append(f"| {rec['bank']} | {item['kept']['bank']} | {rec['stem'][:110]} |")
    lines.append("")

    lines.append(f"## Dropped as malformed ({len(malformed)})")
    lines.append("")
    if malformed:
        lines.append("| bank | options | stem |")
        lines.append("| --- | --- | --- |")
        for rec in malformed:
            lines.append(f"| {rec['bank']} | {len(rec.get('options') or [])} | {rec['stem'][:100]} |")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(C.OUT_DIR))
    args = parser.parse_args(argv)
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    canonical = load_canonical(C.CANONICAL_JSON)
    legacy = load_legacy(C.LEGACY_JSONL)
    raw = json.loads(C.CANONICAL_JSON.read_text())
    systems = {rec["system"] for rec in canonical}

    result = link(canonical, legacy)

    ambiguous = [{"legacy": legacy[i]} for i in result["ambiguous"]]
    malformed = [legacy[i] for i in result["unmatched"] if not is_wellformed(legacy[i])]

    additions = []
    withheld = []
    for index in result["unmatched"]:
        rec = legacy[index]
        if not is_wellformed(rec):
            continue
        classification = classify(rec, systems, trust_label=label_is_trusted(rec["bank"]))
        if classification["confidence"] < C.MIN_CONFIDENCE or not classification["subject"]:
            withheld.append({"legacy": rec, "classification": classification})
            continue
        additions.append({**rec, **classification})

    dedupe = dedupe_within(additions)
    within_duplicates = [
        {"legacy": additions[dup], "kept": additions[kept]}
        for kept, dup in dedupe["duplicates"]
    ]
    additions = [additions[i] for i in dedupe["kept"]]

    additions = mint_ids(additions, canonical)

    rows = emit._grouped_rows(canonical, additions)
    count = emit.write_questions_jsonl(canonical, additions, out_dir / "questions.jsonl")
    emit.write_provenance(additions, out_dir / "provenance.jsonl")
    emit.write_data_js(canonical, additions, raw["groups"], raw["tips"], out_dir / "data.js")
    review = _review_markdown(ambiguous, withheld, within_duplicates, malformed)
    (out_dir / "review.md").write_text(review, encoding="utf-8")

    served_text = (out_dir / "questions.jsonl").read_text(encoding="utf-8")
    gate_records = [
        {
            "id": row["id"],
            "subject_id": row["subject_id"],
            "system": row["sys"],
            "stem": row["q"],
            "options": row["options"],
            "answer": row["answer"],
            "layers": row["layers"],
        }
        for row in rows
    ]
    errors = run_gates(canonical, gate_records, served_text)

    print(f"canonical      {len(canonical)}")
    print(f"legacy records {len(legacy)}")
    print(f"linked         {len(result['linked'])} (exact {result['by_exact']}, options {result['by_options']}, fuzzy {result['by_fuzzy']})")
    print(f"ambiguous      {len(ambiguous)}")
    print(f"additions      {len(additions)}")
    print(f"withheld       {len(withheld)}")
    print(f"within-dupes   {len(within_duplicates)}")
    print(f"malformed      {len(malformed)}")
    print(f"served total   {count}")

    if errors:
        print("\nGATES FAILED:")
        for error in errors:
            print(f"  - {error}")
        return 1
    print("\nall gates passed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
